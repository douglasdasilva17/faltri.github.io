						<h2>Conheça um pouco da trajetória do Triathlon Alagoano</h2><br>
						<h3>Fundação e primeiros passos</h3>
						<p>A Federação Alagoana de Triathlon, conhecida pela sigla
							<strong>Faltri</strong> ou <strong>FALTRI</strong>, foi fundada em agosto de 2001.
						</p>
						<p>Desde seu início, a missão central da Faltri foi fomentar e
							organizar o triathlon no
							estado de Alagoas, articular um calendário de provas, apoiar clubes, atletas e promover a
							modalidade de
							forma estruturada.</p>
						<p>No seu material de apresentação <em>“Construindo Sonhos”</em>, a entidade se
							apresenta como aquela que
							“assumiu o desafio de proporcionar o desenvolvimento e crescimento do triathlon” no
							estado.</p>

						<h3>Primeiras gestões e liderança feminina</h3>
						<p>A triatleta alagoana <strong>Adriana Mangabeira</strong> foi
							eleita presidente da
							Federação em 2017, sendo
							reconhecida como a primeira mulher a tomar esse cargo na entidade.</p>
						<p>Adriana já era uma das fundadoras da Faltri e tem longa trajetória no triathlon: ela
							se considera uma das
							primeiras alagoanas a representar o estado em competições nacionais e
							internacionais, bem como a ser
							“Ironman” no estado.</p>
						<p>Ao assumir, ela declarou que queria praticar uma gestão com o lema <em>“Triathlon
								Para Todos”</em>, com foco
							em inclusão social, apoio a categorias de base, paratriathlon, e levar o esporte
							também a pessoas com menos
							acesso.</p>
						<p>A eleição de uma mulher para presidir a entidade foi tratada como um momento
							simbólico de avanço e afirmação
							de representatividade no esporte alagoano.</p>

						<h3>Estrutura organizacional, registro e filiação</h3>
						<p>A Faltri está oficialmente vinculada à <a href="https://cbtri.org.br/"><strong>Confederação
									Brasileira de Triathlon
									(CBTri)</strong></a> como uma
							das federações estaduais.</p>
						<p>Na página da CBTri, ela aparece listada com o nome, endereço e contato: presidente
							atual, sede e demais
							informações.</p>
						<p>Também consta nos registros oficiais de entidades sociais (mapas OSC) com seus dados
							públicos, como endereço
							e ano de fundação.</p>
						<p>Para que um atleta possa competir oficialmente e contar para rankings
							nacionais/estaduais, é necessário ter o
							registro federativo pela federação local.</p>

						<h3>Desenvolvimento de provas estaduais e parcerias</h3>
						<p>Uma das tarefas principais da Faltri é organizar o calendário de
							eventos de triathlon
							no estado: provas nas
							categorias sprint, olímpico, provas para iniciação, e etapas do Campeonato Alagoano.
						</p>
						<p>Por exemplo, em 2017 a Faltri anunciou a abertura de inscrições para a 1ª etapa do
							Campeonato Alagoano de
							Triathlon, com apoio de clubes e participação de atletas de vários estados,
							inclusive com categorias
							infantis.</p>
						<p>Em 2019, houve uma reestruturação e criação da federação estadual (ou reorganização,
							mencionada como
							“Fetrial”) para que fosse possível formatar e realizar provas, com envolvimento de
							cerca de 200 atletas em
							várias categorias (Mini-Sprint, Sprint, Olímpico e revezamento).</p>
						<p>O presidente da Fetrial (na época) destacou que, “começando do zero, sem nenhum
							capital”, conseguiram fazer
							uma prova de alto nível e já projetar novas etapas.</p>
						<p>Além disso, a Faltri já apoiou a realização de etapas do triathlon mais amplo, como
							provas em orla de praias,
							e colabora com clubes, assessorias esportivas e organizadores locais para que o
							esporte se fortaleça em
							Alagoas.</p>
						<p>Em notícias regionais, por exemplo, a Faltri divulgou que estavam abertas inscrições
							para a 3ª etapa do
							Campeonato Alagoano de Triathlon a ser realizada na orla de Pajuçara, com a
							expectativa de atrair
							participantes locais e de outros estados.</p>

						<h3>Desafios, mudanças e liderança atual</h3>
						<p>Como muitas entidades esportivas de estado, a Faltri enfrentou
							desafios de recursos,
							visibilidade,
							envolvimento social e adaptação às regras nacionais.</p>
						<p>Há processos judiciais mencionados que envolvem a Federação (por exemplo, em
							plataformas de Justiça) — embora
							não encontrei detalhes públicos de processos graves ou que afetem sua operação
							diária.</p>
						<p>Segundo os registros da CBTri atuais, o presidente da Federação Alagoana de Triathlon
							é <strong>Higino José
								dos Anjos Vieira</strong>.</p>
						<p>Assim, a entidade passou por diferentes lideranças e ciclos, buscando ajustar sua
							atuação à realidade local,
							apoiar atletas amadores, promover provas estaduais com qualidade e integrar o
							triathlon de Alagoas ao
							cenário nacional.</p>

						<h3>Impactos e legado</h3>
						<p>A Faltri tem exercido papel central no fortalecimento do triathlon
							em Alagoas. Entre
							os impactos:</p>
						<ul>
							<li>Organização sistemática de provas estaduais e regionais, gerando oportunidades
								de competição para
								atletas locais.</li>
							<li>Inclusão de categorias de base e de iniciação, o que ajuda a formar atletas
								jovens.</li>
							<li>Disseminação do paratriathlon como parte de uma visão mais inclusiva.</li>
							<li>Maior visibilidade para o esporte no estado, atraindo interesse de
								patrocinadores e mídia local.</li>
						</ul>
						<p>Embora ainda existam desafios (infraestrutura, financiamento, logística em regiões
							interioranas), a
							trajetória da Faltri mostra um empenho persistente por consolidar o triathlon em
							Alagoas e articular com
							entidades nacionais para favorecer seus atletas.</p>
